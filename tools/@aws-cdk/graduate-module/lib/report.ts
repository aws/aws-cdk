import * as fs from 'fs';
import * as path from 'path';

export type Severity = 'info' | 'review' | 'warn' | 'manual';

export interface ReportEntry {
  readonly severity: Severity;
  /** The transform/step that produced this entry, e.g. `imports`, `awslint`. */
  readonly step: string;
  readonly message: string;
  /** Optional file the entry relates to (repo-relative preferred). */
  readonly file?: string;
}

/**
 * Accumulates a human-review checklist across the whole run and writes it to
 * `graduation-report.md`. The "auto + flag for review" model depends on this:
 * every risky/auto transform records what it did so a maintainer can verify the
 * diff before opening the PR.
 */
export class GraduationReport {
  private readonly entries: ReportEntry[] = [];

  constructor(private readonly service: string) {}

  add(entry: ReportEntry): void {
    this.entries.push(entry);
  }

  info(step: string, message: string, file?: string) {
    this.add({ severity: 'info', step, message, file });
  }

  /** A transform completed automatically but a human should verify the result. */
  review(step: string, message: string, file?: string) {
    this.add({ severity: 'review', step, message, file });
  }

  warn(step: string, message: string, file?: string) {
    this.add({ severity: 'warn', step, message, file });
  }

  /** Something could not be automated and requires a manual follow-up. */
  manual(step: string, message: string, file?: string) {
    this.add({ severity: 'manual', step, message, file });
  }

  get hasManualItems(): boolean {
    return this.entries.some((e) => e.severity === 'manual');
  }

  private section(title: string, severity: Severity): string {
    const rows = this.entries.filter((e) => e.severity === severity);
    if (rows.length === 0) {
      return '';
    }
    const lines = rows.map((e) => {
      const loc = e.file ? ` \`${e.file}\`` : '';
      return `- **[${e.step}]**${loc} — ${e.message}`;
    });
    return `## ${title}\n\n${lines.join('\n')}\n\n`;
  }

  render(): string {
    const icons: Record<Severity, string> = {
      manual: '🔴 Manual follow-up required',
      warn: '🟡 Warnings',
      review: '🔵 Auto-applied — please review',
      info: '⚪ Informational',
    };
    let out = `# Graduation report: ${this.service}\n\n`;
    out += 'Generated by `graduate-module`. Review every item below before opening the PR.\n\n';
    for (const sev of ['manual', 'warn', 'review', 'info'] as Severity[]) {
      out += this.section(icons[sev], sev);
    }
    return out;
  }

  writeTo(dir: string): string {
    const file = path.join(dir, 'graduation-report.md');
    fs.writeFileSync(file, this.render());
    return file;
  }
}
