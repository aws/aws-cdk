#!/usr/bin/env node
import * as integ from '@aws-cdk/integ-tests-alpha';
import * as cdk from 'aws-cdk-lib';
import * as ec2 from 'aws-cdk-lib/aws-ec2';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as kms from 'aws-cdk-lib/aws-kms';
import * as lambda from 'aws-cdk-lib/aws-lambda';

import { REDSHIFT_COLUMN_ID } from 'aws-cdk-lib/cx-api';
import type * as constructs from 'constructs';
import * as redshift from '../lib';

const useColumnIds = { [REDSHIFT_COLUMN_ID]: false };
const app = new cdk.App({
  postCliContext: {
    '@aws-cdk/aws-lambda:createNewPoliciesWithAddToRolePolicy': true,
    '@aws-cdk/aws-lambda:useCdkManagedLogGroup': false,
  },
  context: {
    ...useColumnIds,
  },
});

const stack = new cdk.Stack(app, 'aws-cdk-redshift-cluster-database');

cdk.Aspects.of(stack).add({
  visit(node: constructs.IConstruct) {
    if (cdk.CfnResource.isCfnResource(node)) {
      node.applyRemovalPolicy(cdk.RemovalPolicy.DESTROY);
    }
  },
});

const key = new kms.Key(stack, 'custom-kms-key');
const vpc = new ec2.Vpc(stack, 'Vpc', { restrictDefaultSecurityGroup: false });
const databaseName = 'my_db';
const cluster = new redshift.Cluster(stack, 'Cluster', {
  vpc: vpc,
  nodeType: redshift.NodeType.RA3_LARGE,
  vpcSubnets: {
    subnetType: ec2.SubnetType.PUBLIC,
  },
  masterUser: {
    masterUsername: 'admin',
  },
  defaultDatabaseName: databaseName,
  publiclyAccessible: true,
  encryptionKey: key,
});

cluster.addToParameterGroup('enable_user_activity_logging', 'true');

const databaseOptions = {
  cluster: cluster,
  databaseName: databaseName,
};
const user = new redshift.User(stack, 'User', databaseOptions);
const table = new redshift.Table(stack, 'Table', {
  ...databaseOptions,
  tableName: 'public.IntegTable',
  tableColumns: [
    { name: 'col1', dataType: 'varchar(4)', distKey: true, comment: 'A test column', encoding: redshift.ColumnEncoding.LZO },
    { name: 'col2', dataType: 'float', sortKey: true, comment: 'A test column' },
    { name: 'col3', dataType: 'float', comment: 'A test column', encoding: redshift.ColumnEncoding.RAW },
  ],
  distStyle: redshift.TableDistStyle.KEY,
  sortStyle: redshift.TableSortStyle.INTERLEAVED,
  tableComment: 'A test table',
});
table.grant(user, redshift.TableAction.INSERT, redshift.TableAction.DELETE);

const tableWithAutoGeneratedName = new redshift.Table(stack, 'TableWithAutoGeneratedName', {
  ...databaseOptions,
  tableColumns: [
    { name: 'col1', dataType: 'varchar(4)', distKey: true, comment: 'A test column', encoding: redshift.ColumnEncoding.LZO },
    { name: 'col2', dataType: 'float', sortKey: true, comment: 'A test column' },
    { name: 'col3', dataType: 'float', comment: 'A test column', encoding: redshift.ColumnEncoding.RAW },
  ],
  distStyle: redshift.TableDistStyle.KEY,
  sortStyle: redshift.TableSortStyle.INTERLEAVED,
  tableComment: 'A test table with table name auto generated',
});
tableWithAutoGeneratedName.grant(user, redshift.TableAction.INSERT, redshift.TableAction.UPDATE);

// The Data API shows a statement only to the role that ran it, so one function runs the query and reads its
// status and result.
const privilegeQuery = new lambda.Function(stack, 'PrivilegeQuery', {
  runtime: lambda.Runtime.NODEJS_22_X,
  handler: 'index.handler',
  timeout: cdk.Duration.minutes(1),
  environment: {
    CLUSTER_NAME: cluster.clusterName,
    DATABASE_NAME: databaseName,
    SECRET_ARN: cluster.secret!.secretArn,
    USER_NAME: user.username,
  },
  code: lambda.Code.fromInline(`
const { RedshiftDataClient, ExecuteStatementCommand, DescribeStatementCommand, GetStatementResultCommand } = require('@aws-sdk/client-redshift-data');
const client = new RedshiftDataClient();
exports.handler = async () => {
  const { Id } = await client.send(new ExecuteStatementCommand({
    ClusterIdentifier: process.env.CLUSTER_NAME,
    Database: process.env.DATABASE_NAME,
    SecretArn: process.env.SECRET_ARN,
    Sql: "SELECT has_table_privilege(:grantee, 'public.integtable', 'INSERT'), has_table_privilege(:grantee, 'public.integtable', 'DELETE')",
    Parameters: [{ name: 'grantee', value: process.env.USER_NAME }],
  }));
  for (;;) {
    const statement = await client.send(new DescribeStatementCommand({ Id }));
    if (statement.Status === 'FINISHED') break;
    if (statement.Status === 'FAILED' || statement.Status === 'ABORTED') throw new Error(statement.Status + ': ' + statement.Error);
    await new Promise((resolve) => setTimeout(resolve, 1000));
  }
  const { Records } = await client.send(new GetStatementResultCommand({ Id }));
  return Records.map((row) => row.map((field) => field.booleanValue));
};
`),
});
cluster.secret!.grantRead(privilegeQuery);
privilegeQuery.addToRolePolicy(new iam.PolicyStatement({
  actions: ['redshift-data:ExecuteStatement'],
  resources: [stack.formatArn({ service: 'redshift', resource: 'cluster', resourceName: cluster.clusterName, arnFormat: cdk.ArnFormat.COLON_RESOURCE_NAME })],
}));
privilegeQuery.addToRolePolicy(new iam.PolicyStatement({
  actions: ['redshift-data:DescribeStatement', 'redshift-data:GetStatementResult'],
  resources: ['*'],
}));

const integTest = new integ.IntegTest(app, 'redshift-cluster-database-integ', {
  testCases: [stack],
});

integTest.assertions.invokeFunction({
  functionName: privilegeQuery.functionName,
}).expect(integ.ExpectedResult.objectLike({
  Payload: '[[true,true]]',
}));
